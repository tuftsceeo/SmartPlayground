#!/usr/bin/env python3
"""Generate js/ledicons/shapes5.js from the wand firmware's leds.py and main.py.

The file holds the 5x5 SHAPE_* LED index lists and the named LED colors a
[GAME_ICON: SHAPE_X, COLOR] marker can name, for the game-card thumbnails,
and main.py's GAME_ICON table (each built-in game's start signature), for
the example-game cards.

Sources: Bag3/Code/Wand Module/lib/leds.py and main.py (the Mock Wand).
Run from ChatBroadcast/:
    python tools/sync_shapes5.py          write js/ledicons/shapes5.js
    python tools/sync_shapes5.py --check  exit 1 if the file differs
"""
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
SRC = HERE.parents[1] / "Wand Module" / "lib" / "leds.py"
MAIN = HERE.parents[1] / "Wand Module" / "main.py"
OUT = HERE.parent / "js" / "ledicons" / "shapes5.js"

SHAPE_RE = re.compile(r"^(SHAPE_[A-Za-z0-9_]+)\s*=\s*\(([0-9,\s]*)\)\s*(?:#.*)?$")
COLOR_RE = re.compile(r"^([A-Z_]+)\s*=\s*\((\d+),\s*(\d+),\s*(\d+)\)")
# A GAME_ICON entry: "slug": (SHAPE_X, COLOR),
ICON_RE = re.compile(r'^\s*"(\w+)":\s*\((SHAPE_[A-Za-z0-9_]+),\s*([A-Z_]+)\),')


def game_icons():
    """main.py's GAME_ICON dict as {slug: (shape, color)}."""
    out, inside = {}, False
    for line in MAIN.read_text().splitlines():
        if line.startswith("GAME_ICON = {"):
            inside = True
            continue
        if inside and line.startswith("}"):
            break
        m = ICON_RE.match(line) if inside else None
        if m:
            out[m.group(1)] = (m.group(2), m.group(3))
    if not out:
        raise SystemExit(f"no GAME_ICON entries found in {MAIN}")
    return out


def build():
    shapes, colors = {}, {}
    for line in SRC.read_text().splitlines():
        m = SHAPE_RE.match(line)
        if m:
            shapes[m.group(1)] = [int(x) for x in m.group(2).replace(" ", "").split(",") if x]
            continue
        m = COLOR_RE.match(line)
        if m and m.group(1) not in ("OFF", "BLACK"):
            colors[m.group(1)] = [int(m.group(i)) for i in (2, 3, 4)]
    lines = [
        "/**",
        " * shapes5.js -- generated by tools/sync_shapes5.py from",
        " * Bag3/Code/Wand Module/lib/leds.py and main.py. Do not edit by hand.",
        " *",
        " * SHAPE_* 5x5 LED index lists (row-major, 0-24), the LED colors a",
        " * [GAME_ICON: SHAPE_X, COLOR] marker can name, and each built-in",
        " * game's start signature (main.py GAME_ICON).",
        " */",
        "",
        "export const SHAPES5 = {",
    ]
    for name, idx in shapes.items():
        lines.append(f"    {name}: [{', '.join(map(str, idx))}],")
    lines += ["};", "", "export const LED_COLORS = {"]
    for name, rgb in colors.items():
        lines.append(f"    {name}: [{', '.join(map(str, rgb))}],")
    lines += ["};", "", "export const GAME_ICONS = {"]
    for slug, (shape, color) in game_icons().items():
        if shape not in shapes or color not in colors:
            raise SystemExit(f"GAME_ICON {slug}: {shape}/{color} not in leds.py")
        lines.append(f'    {slug}: {{ shape: "{shape}", color: "{color}" }},')
    lines += ["};", ""]
    return "\n".join(lines)


def main():
    text = build()
    if "--check" in sys.argv:
        if not OUT.exists() or OUT.read_text() != text:
            print(f"{OUT} is out of date; run tools/sync_shapes5.py")
            return 1
        print("shapes5.js is up to date")
        return 0
    OUT.write_text(text)
    print(f"wrote {OUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
