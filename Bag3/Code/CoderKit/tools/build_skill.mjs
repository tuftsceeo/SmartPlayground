// Run from CoderKit/:  node tools/build_skill.mjs
// Builds skill/ (and skill.zip): SKILL.md stays hand-written; everything
// else is regenerated from ChatBroadcast so the priming never drifts.
import { readFileSync, writeFileSync, mkdirSync, rmSync, copyFileSync, cpSync, existsSync, readdirSync, statSync } from 'node:fs';
import { execFileSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
import { knowledgePaths } from '../../ChatBroadcast/js/prompt/buildRequest.js';
import { EXAMPLES } from '../../ChatBroadcast/js/examples.js';
import { systemBlocks } from '../coderkit.js';
import { systemText } from '../brains.js';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const cb = join(root, '../ChatBroadcast');
const files = Object.fromEntries([...knowledgePaths(), 'knowledge/simulator.md'].map(p => [p, readFileSync(join(cb, p), 'utf8')]));
const games = Object.fromEntries(EXAMPLES.filter(e => e.vendorGame).map(e => [e.vendorGame, readFileSync(join(root, '../Simulator/vendor/games', e.vendorGame + '.py'), 'utf8')]));

mkdirSync(join(root, 'build'), { recursive: true });
writeFileSync(join(root, 'build/knowledge.json'), JSON.stringify(files));
writeFileSync(join(root, 'build/examples.json'), JSON.stringify(games));

const out = join(root, 'skill');
for (const d of ['knowledge', 'kit', 'templates']) rmSync(join(out, d), { recursive: true, force: true });
mkdirSync(join(out, 'knowledge'), { recursive: true });
mkdirSync(join(out, 'kit'), { recursive: true });
mkdirSync(join(out, 'templates'), { recursive: true });

// The knowledge, and the exact priming Chat Broadcast sends.
cpSync(join(cb, 'knowledge'), join(out, 'knowledge'), { recursive: true });
writeFileSync(join(out, 'priming.md'), '<!-- Generated by tools/build_skill.mjs from ChatBroadcast. Do not edit. -->\n\n' + systemText(systemBlocks(files)));

// The kit as one script for artifacts.
execFileSync(join(root, 'node_modules/.bin/esbuild'), [
    'artifact-entry.js', '--bundle', '--format=iife', '--minify', '--loader:.json=json',
    '--outfile=' + join(out, 'kit/coderkit.js'),
], { cwd: root, stdio: 'inherit' });

// Templates, and the artifact versions of the same pages (no doctype or
// head; a <title> and an explicit background), so the two never drift.
mkdirSync(join(root, 'artifact'), { recursive: true });
// Expand frontends/src/*.html: <style data-inline="path"> gets that file's CSS.
for (const f of existsSync(join(root, 'frontends/src')) ? readdirSync(join(root, 'frontends/src')) : []) {
    const src = readFileSync(join(root, 'frontends/src', f), 'utf8');
    writeFileSync(join(root, 'frontends', f), src.replace(/<style data-inline="([^"]+)"><\/style>/g, (_, p) =>
        '<style>/* ' + p + ' */\n' + readFileSync(join(root, 'frontends', p), 'utf8') + '\n</style>'));
}
for (const [name, title, sim] of [['blank', 'Blank Playground IDE', false], ['full', 'Full Playground IDE', true], ['chatbroadcast', 'ChatBroadcast-style Playground IDE', true]]) {
    const html = readFileSync(join(root, `frontends/${name}.html`), 'utf8');
    copyFileSync(join(root, `frontends/${name}.html`), join(out, `templates/${name}.html`));
    const scripts = [...html.matchAll(/<script src="[^"]+"><\/script>/g)].map(m => m[0]).join('\n');
    const body = html.match(/<body([^>]*)>([\s\S]*)<\/body>/);
    const attrs = body[1].replace(/\bh-screen\b/, 'h-full');
    writeFileSync(join(root, `artifact/${name}-ide.html`),
        `<title>${title}</title>\n<style>html,body{height:100%;margin:0;background:#fff;color:#111}</style>\n${sim ? '<meta name="coderkit-simulator">\n' : ''}${scripts}\n<div${attrs}>${body[2]}</div>\n`);
}
copyFileSync(join(out, 'kit/coderkit.js'), join(root, 'artifact/coderkit.js'));
copyFileSync(join(root, 'check.js'), join(out, 'kit/check.js'));

rmSync(join(root, 'skill.zip'), { force: true });
execFileSync('zip', ['-qr', join(root, 'skill.zip'), '.'], { cwd: out });
console.log('skill/ and skill.zip built');

// Files an artifact with the simulator publishes beside its page (Artifact
// tool `files`): the Simulator as in the repo, and Pyodide (fetched once
// into build/pyodide by hand; see README). .py goes as text/plain.
const sim = join(root, '../Simulator');
const SKIP = /(^|\/)(tests|tools|\.[^/]*|node_modules)(\/|$)|\.md$|index\.html$|pytest\.ini$/;
const simFiles = {};
(function walk(dir) {
    for (const f of readdirSync(join(sim, dir))) {
        const rel = dir ? `${dir}/${f}` : f;
        if (SKIP.test(rel)) continue;
        if (statSync(join(sim, rel)).isDirectory()) walk(rel);
        else if (f.endsWith('.svg')) {
            // Artifacts refuse XML processing instructions other than the
            // leading declaration (Illustrator adds <?xpacket ...?>).
            const dest = join(root, 'build/sim-svg', rel);
            mkdirSync(dirname(dest), { recursive: true });
            writeFileSync(dest, readFileSync(join(sim, rel), 'utf8').replace(/<\?xpacket[^>]*\?>/g, '').replace(/(?!^)<\?(?!xml\s)[^>]*\?>/g, ''));
            simFiles[`Simulator/${rel}`] = dest;
        }
        else if (/\.(js|json|py|txt|png)$/.test(f)) simFiles[`Simulator/${rel}`] = /\.(py|txt)$/.test(f) ? { from: join(sim, rel), contentType: 'text/plain' } : join(sim, rel);
    }
})('');
const PY = ['pyodide.js', 'pyodide.asm.js', 'pyodide.asm.wasm', 'pyodide-lock.json', 'python_stdlib.txt'];
const missing = PY.filter(f => !existsSync(join(root, 'build/pyodide', f)));
if (missing.length) console.warn('build/pyodide is missing ' + missing.join(', ') + ' (see README); the simulator will not run in artifacts.');
for (const f of PY) simFiles[`pyodide/${f}`] = join(root, 'build/pyodide', f);
simFiles['coderkit.js'] = join(root, 'artifact/coderkit.js');
writeFileSync(join(root, 'artifact/full-files.json'), JSON.stringify(simFiles, null, 1));
copyFileSync(join(root, 'artifact/full-files.json'), join(out, 'kit/full-files.json'));
console.log(`artifact/full-files.json: ${Object.keys(simFiles).length} files`);
