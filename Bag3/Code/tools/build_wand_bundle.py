#!/usr/bin/env python3
"""Build the Bag3 wand bundle the Live_Page Flasher uploads.

The Flasher can't run mpy-cross in the browser, so this does it here and the
result is committed:

    Bag3/Code/Wand Module/flash_bundle/wand_main.mpy   main.py compiled (mpy-cross)
    Bag3/Code/Wand Module/flash_bundle/main.py         one-line stub: import wand_main
    Bag3/Code/Wand Module/flash_bundle/flash_manifest.json
                                                every file to upload, in order

All other files are listed by their source path in the repo, so only the
compiled pieces are copies. The file list and order come from deploy.py
(manifest.js WAND_FILES, boot.py then wand_main.mpy then the stub main.py).

Re-run and commit flash_bundle/ whenever Wand Module code changes:

    python3 tools/build_wand_bundle.py           # rebuild
    python3 tools/build_wand_bundle.py --check   # exit 1 if flash_bundle/ is stale

Needs mpy-cross 1.28.0.post2 (pip install --user mpy-cross==1.28.0.post2).
"""

import argparse
import hashlib
import json
import os
import shutil
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import deploy  # noqa: E402

CODE = deploy.CODE
REPO_ROOT = os.path.dirname(os.path.dirname(CODE))
WAND_DIR = os.path.join(CODE, "Wand Module")
BUILD_DIR = os.path.join(WAND_DIR, "flash_bundle")
MANIFEST = os.path.join(BUILD_DIR, "flash_manifest.json")


def _sha(path):
    with open(path, "rb") as f:
        return hashlib.sha256(f.read()).hexdigest()


def _repo_rel(path):
    return os.path.relpath(path, REPO_ROOT).replace(os.sep, "/")


def build():
    """Write flash_bundle/ fresh. Returns the manifest dict."""
    files = deploy._files_for("wand", code_only=False)  # compiles into a tmp dir
    os.makedirs(BUILD_DIR, exist_ok=True)
    entries = []
    for local, remote in files:
        if not os.path.realpath(local).startswith(os.path.realpath(WAND_DIR)):
            # wand_main.mpy / stub main.py from deploy's tmp dir -> flash_bundle/
            dest = os.path.join(BUILD_DIR, os.path.basename(local))
            shutil.copyfile(local, dest)
            local = dest
        entries.append({"repo": _repo_rel(local), "device": remote.lstrip("/")})
    manifest = {
        "about": "Bag3 wand bundle for Live_Page/Flasher. Generated by "
                 "Bag3/Code/tools/build_wand_bundle.py; do not edit by hand.",
        "main_py_sha256": _sha(os.path.join(WAND_DIR, "main.py")),
        "remove_before_upload": ["boot_ok"],
        "files": entries,
    }
    with open(MANIFEST, "w") as f:
        json.dump(manifest, f, indent=2)
        f.write("\n")
    return manifest


def check():
    """flash_bundle/ is stale if main.py changed or WAND_FILES changed since it was built."""
    try:
        with open(MANIFEST) as f:
            old = json.load(f)
    except OSError:
        print("no flash_bundle/flash_manifest.json -- run build_wand_bundle.py")
        return 1
    problems = []
    if old.get("main_py_sha256") != _sha(os.path.join(WAND_DIR, "main.py")):
        problems.append("main.py changed since wand_main.mpy was built")
    listed = {e["device"] for e in old["files"]}
    want = {r.lstrip("/") for _, r in deploy._manifest_files(WAND_DIR, "manifest.js", "WAND_FILES")}
    want = (want - {"main.py"}) | {"main.py", "wand_main.mpy"}
    if listed != want:
        problems.append("manifest.js WAND_FILES differs: missing %s, extra %s"
                        % (sorted(want - listed), sorted(listed - want)))
    for p in problems:
        print("STALE: " + p)
    if not problems:
        print("flash_bundle/ is up to date")
    return 1 if problems else 0


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--check", action="store_true", help="report staleness, write nothing")
    args = ap.parse_args()
    if args.check:
        sys.exit(check())
    m = build()
    print("wrote %s (%d files)" % (_repo_rel(MANIFEST), len(m["files"])))


if __name__ == "__main__":
    main()
