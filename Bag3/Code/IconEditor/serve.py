#!/usr/bin/env python3
"""
serve.py -- dev server for the Icon Maker web app.

Exists because `python3 -m http.server` lets Chrome cache ES modules
aggressively: `index.html` carries a `?v=N` cache-buster but the modules it
imports do not, so editing e.g. js/pipeline/ledcolor.js and reloading gives
you a stale module and a confusing "does not provide an export named ..."
error. Hard-reloading every time is a bad workflow; sending no-store is the
actual fix.

    python3 serve.py            # http://localhost:8757/IconEditor/webapp/
    python3 serve.py 9000       # different port

It serves Bag3/Code/ (not this folder) because the web app imports
ChatBroadcast/js/ledicons/ by relative path, the same layout ChatBroadcast
uses to load the app embedded. Bound to 127.0.0.1 only.

POST /api/icon is the dev-mode Save: {"name", "text", "overwrite"} writes
Stations/IconDisplay/icons/<name>.py (the source-of-truth icon library),
then runs ChatBroadcast/tools/sync_icons.py and --station so defaultIcons.js
and IconEditor/icons/ follow. An existing icon is refused (409) unless
overwrite is true. No git: the developer reviews and commits.

Web Serial needs a secure context -- localhost qualifies, so this is fine.
"""

import json
import os
import re
import subprocess
import sys
import http.server
import socketserver
from functools import partial

PORT = int(sys.argv[1]) if len(sys.argv) > 1 else 8757
HERE = os.path.dirname(os.path.abspath(__file__))
CODE = os.path.dirname(HERE)
DEVICE_ICONS = os.path.join(CODE, "Stations", "IconDisplay", "icons")
SYNC = os.path.join(CODE, "ChatBroadcast", "tools", "sync_icons.py")
NAME_RE = re.compile(r"^[a-z0-9_]{1,40}$")
TUPLE_RE = re.compile(r"\((\d+),\s*(\d+),\s*(\d+)\)")


def icon_file(pixels, note):
    """Canonical device icon text: 16 rows of 16 duty tuples (see icons/heart.py)."""
    lines = ["# " + note, "SIZE = (16, 16)", "ICON = ("]
    for r in range(16):
        row = pixels[r * 16:(r + 1) * 16]
        lines.append("    " + " ".join("(%d, %d, %d)," % p for p in row))
    lines.append(")")
    return "\n".join(lines) + "\n"


class NoCacheHandler(http.server.SimpleHTTPRequestHandler):
    def end_headers(self):
        self.send_header("Cache-Control", "no-store, no-cache, must-revalidate, max-age=0")
        self.send_header("Pragma", "no-cache")
        self.send_header("Expires", "0")
        super().end_headers()

    def do_POST(self):
        if self.path != "/api/icon":
            return self._reply(404, {"error": "not found"})
        try:
            body = json.loads(self.rfile.read(int(self.headers.get("Content-Length", 0))))
        except (ValueError, TypeError):
            return self._reply(400, {"error": "bad JSON"})
        name = str(body.get("name", ""))
        if not NAME_RE.match(name):
            return self._reply(400, {"error": "name must be a-z, 0-9, _"})
        pixels = [tuple(int(v) for v in m) for m in TUPLE_RE.findall(str(body.get("text", "")))]
        if len(pixels) != 256 or any(v > 255 for p in pixels for v in p):
            return self._reply(400, {"error": "icon must be 256 (r, g, b) duty tuples, 0-255"})
        path = os.path.join(DEVICE_ICONS, name + ".py")
        existed = os.path.exists(path)
        if existed and body.get("overwrite") is not True:
            return self._reply(409, {"error": "exists", "name": name})
        with open(path, "w") as f:
            f.write(icon_file(pixels, "Generated by Icon Maker (web)"))
        out = []
        for extra in ([], ["--station"]):
            r = subprocess.run([sys.executable, SYNC] + extra, cwd=os.path.dirname(os.path.dirname(SYNC)),
                               capture_output=True, text=True)
            out.append((r.stdout + r.stderr).strip()[-400:])
            if r.returncode:
                return self._reply(500, {"error": "sync_icons.py failed", "log": out})
        sys.stderr.write("%s %s\n" % ("replaced" if existed else "added", os.path.relpath(path, CODE)))
        self._reply(200, {"name": name, "path": os.path.relpath(path, CODE), "replaced": existed, "log": out})

    def _reply(self, code, obj):
        data = json.dumps(obj).encode()
        self.send_response(code)
        self.send_header("Content-Type", "application/json")
        self.send_header("Content-Length", str(len(data)))
        self.end_headers()
        self.wfile.write(data)

    def log_message(self, fmt, *args):
        # Quieter: skip the 200s, keep anything that went wrong.
        msg = fmt % args
        if " 200 " not in msg and " 304 " not in msg:
            sys.stderr.write("%s\n" % msg)


class ReusableServer(socketserver.TCPServer):
    allow_reuse_address = True  # avoids "Address already in use" on quick restarts


if __name__ == "__main__":
    handler = partial(NoCacheHandler, directory=CODE)
    with ReusableServer(("127.0.0.1", PORT), handler) as httpd:
        print(f"Icon Maker dev server -> http://localhost:{PORT}/IconEditor/webapp/")
        print("(no-store headers set, so a plain reload always picks up edits)")
        try:
            httpd.serve_forever()
        except KeyboardInterrupt:
            print("\nstopped")
