#!/usr/bin/env python3
"""Generate js/ledicons/shapes5.js from the wand firmware's leds.py.

The file holds the 5x5 SHAPE_* LED index lists and the named LED colors a
[GAME_ICON: SHAPE_X, COLOR] marker can name, for the saved-game thumbnails.

Source: Bag3/Code/Wand Module/lib/leds.py (the Mock Wand).
Run from ChatBroadcast/:
    python tools/sync_shapes5.py          write js/ledicons/shapes5.js
    python tools/sync_shapes5.py --check  exit 1 if the file differs
"""
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
SRC = HERE.parents[2] / "Wand Module" / "lib" / "leds.py"
OUT = HERE.parent / "js" / "ledicons" / "shapes5.js"

SHAPE_RE = re.compile(r"^(SHAPE_[A-Z0-9_]+)\s*=\s*\(([0-9,\s]*)\)\s*(?:#.*)?$")
COLOR_RE = re.compile(r"^([A-Z_]+)\s*=\s*\((\d+),\s*(\d+),\s*(\d+)\)")


def build():
    shapes, colors = {}, {}
    for line in SRC.read_text().splitlines():
        m = SHAPE_RE.match(line)
        if m:
            shapes[m.group(1)] = [int(x) for x in m.group(2).replace(" ", "").split(",") if x]
            continue
        m = COLOR_RE.match(line)
        if m and m.group(1) not in ("OFF", "BLACK"):
            colors[m.group(1)] = [int(m.group(i)) for i in (2, 3, 4)]
    lines = [
        "/**",
        " * shapes5.js -- generated by tools/sync_shapes5.py from",
        " * Bag3/Code/Wand Module/lib/leds.py. Do not edit by hand.",
        " *",
        " * SHAPE_* 5x5 LED index lists (row-major, 0-24) and the LED colors a",
        " * [GAME_ICON: SHAPE_X, COLOR] marker can name.",
        " */",
        "",
        "export const SHAPES5 = {",
    ]
    for name, idx in shapes.items():
        lines.append(f"    {name}: [{', '.join(map(str, idx))}],")
    lines += ["};", "", "export const LED_COLORS = {"]
    for name, rgb in colors.items():
        lines.append(f"    {name}: [{', '.join(map(str, rgb))}],")
    lines += ["};", ""]
    return "\n".join(lines)


def main():
    text = build()
    if "--check" in sys.argv:
        if not OUT.exists() or OUT.read_text() != text:
            print(f"{OUT} is out of date; run tools/sync_shapes5.py")
            return 1
        print("shapes5.js is up to date")
        return 0
    OUT.write_text(text)
    print(f"wrote {OUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
